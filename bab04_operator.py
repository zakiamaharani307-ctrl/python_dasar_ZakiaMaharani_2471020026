# BAB 04 - Operator

# Operator Aritmatika
a = 7
b = 3

print("Penjumlahan:", a + b)
print("Pengurangan:", a - b)
print("Perkalian:", a * b)
print("Pembagian:", a / b)
print("Pembagian bulat:", a // b)
print("Modulus:", a % b)
print("Pangkat:", a ** b)

# Urutan operasi
print("Hasil operasi:", 2 + 3 * 4 ** 2)

# Operator Perbandingan
print(5 == 5)
print(5 != 3)
print(7 > 9)
print(2 < 8)
print(5 >= 5)
print(4 <= 1)

# Operator Logika
umur = 20
punya_ktp = True

print(umur >= 17 and punya_ktp)
print(umur < 13 or umur > 60)
print(not punya_ktp)